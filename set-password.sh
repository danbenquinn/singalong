#!/usr/bin/env bash
# set-password.sh — choose the site password. Run it, type the password when asked, then publish.
#
#   bash set-password.sh && bash publish.sh "new password"
#
# Only the SHA-256 hash of the password is stored (in config.js), never the password itself.
# Everyone's phone will ask for the new password the next time the page loads.
cd "$(dirname "$0")"
read -r -s -p "New password: " PW; echo
[ -n "$PW" ] || { echo "empty password, nothing changed"; exit 1; }
HASH="$(printf '%s' "$PW" | shasum -a 256 | cut -d' ' -f1)"
printf '// Generated by set-password.sh — the SHA-256 hash of the site password.\nconst PASSWORD_HASH = "%s";\n' "$HASH" > config.js
echo "config.js updated. Now run: bash publish.sh \"new password\""
